def test_point_at_pos_straight_line_midpoint():
    result = inpx_parser.point_at_pos([[0, 0], [10, 0]], 5)
    assert result == (5.0, 0.0, 0.0)


def test_point_at_pos_right_angle_turn_uses_containing_segment_angle():
    # First segment (0,0)->(10,0) is length 10; pos=15 lands 5 into the
    # second segment (10,0)->(10,10), which points straight "up" (90 deg).
    result = inpx_parser.point_at_pos([[0, 0], [10, 0], [10, 10]], 15)
    assert result == (10.0, 5.0, 90.0)


def test_point_at_pos_clamps_negative_pos_to_start():
    result = inpx_parser.point_at_pos([[0, 0], [10, 0]], -50)
    assert result == (0.0, 0.0, 0.0)


def test_point_at_pos_clamps_overlong_pos_to_end():
    result = inpx_parser.point_at_pos([[0, 0], [10, 0]], 1000)
    assert result == (10.0, 0.0, 0.0)


def test_point_at_pos_returns_none_for_fewer_than_two_points():
    assert inpx_parser.point_at_pos([[0, 0]], 5) is None
    assert inpx_parser.point_at_pos([], 5) is None
    assert inpx_parser.point_at_pos(None, 5) is None


def test_point_at_pos_returns_none_for_none_or_malformed_pos():
    assert inpx_parser.point_at_pos([[0, 0], [10, 0]], None) is None
    assert inpx_parser.point_at_pos([[0, 0], [10, 0]], "not-a-number") is None
    assert inpx_parser.point_at_pos([[0, 0], [10, 0]], float("nan")) is None


def test_point_at_pos_handles_coincident_points_without_raising():
    result = inpx_parser.point_at_pos([[5, 5], [5, 5], [5, 5]], 3)
    assert result is not None
    x, y, _angle = result
    assert (x, y) == (5.0, 5.0)


