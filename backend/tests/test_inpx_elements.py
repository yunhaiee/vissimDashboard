def test_lane_offset_point_rightmost_lane_of_odd_count_offsets_to_right():
    # Eastbound (dx=1,dy=0): right normal is (0,-1). 3 lanes of 3.5m, lane 1
    # (rightmost) center sits 3.5m to the right (negative y) of the centerline.
    result = inpx_parser.lane_offset_point([[0, 0], [100, 0]], 50, 1, [3.5, 3.5, 3.5])
    assert result == (50.0, -3.5, 0.0)


def test_lane_offset_point_leftmost_lane_offsets_to_left():
    result = inpx_parser.lane_offset_point([[0, 0], [100, 0]], 50, 3, [3.5, 3.5, 3.5])
    assert result == (50.0, 3.5, 0.0)


