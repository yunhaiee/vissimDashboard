STRAIGHT_LINK_XML = (
    '<link no="1" name="Straight"><geometry><linkPolyPts>'
    '<linkPolyPoint x="0" y="0" zOffset="0"/><linkPolyPoint x="100" y="0" zOffset="0"/>'
    "</linkPolyPts></geometry><lanes><lane width=\"3.5\"/><lane width=\"3.5\"/></lanes></link>"
)

# A second link (no="2"), a 100m vertical segment from (200,0) to (200,100),
# for the travel-time-measurement tests (which need two distinct links).
SECOND_LINK_XML = (
    '<link no="2" name="Second"><geometry><linkPolyPts>'
    '<linkPolyPoint x="200" y="0" zOffset="0"/><linkPolyPoint x="200" y="100" zOffset="0"/>'
    '</linkPolyPts></geometry><lanes><lane width="3.5"/></lanes></link>'
)


def _root(inner_xml: str) -> ET.Element:
    xml = f'<?xml version="1.0" encoding="UTF-8"?><network>{inner_xml}</network>'
    return ET.fromstring(xml)


def _network_with_link_and(container_xml: str) -> ET.Element:
    return _root(f"<links>{STRAIGHT_LINK_XML}</links>{container_xml}")


def _network_two_links_and(container_xml: str) -> ET.Element:
    return _root(f"<links>{STRAIGHT_LINK_XML}{SECOND_LINK_XML}</links>{container_xml}")


