def test_showcase_network_populates_every_element_type_with_plausible_coordinates(tmp_path: Path):
    out_path = write_showcase(tmp_path)
    net = inpx_parser.parse_network(str(out_path))
    elements = net["elements"]

    all_points = [pt for link in net["links"] for pt in link["points"]]
    min_x = min(pt[0] for pt in all_points)
    max_x = max(pt[0] for pt in all_points)
    min_y = min(pt[1] for pt in all_points)
    max_y = max(pt[1] for pt in all_points)
    margin = 5.0

    def assert_in_bounds(x: float, y: float) -> None:
        assert math.isfinite(x) and math.isfinite(y)
        assert min_x - margin <= x <= max_x + margin
        assert min_y - margin <= y <= max_y + margin

    for key, items in elements.items():
        assert items, f"expected the showcase network to populate elements['{key}']"

    for head in elements["signal_heads"]:
        assert_in_bounds(head["x"], head["y"])
        assert math.isfinite(head["angle"])
    for vi in elements["vehicle_inputs"]:
        assert_in_bounds(vi["x"], vi["y"])
    for rsa in elements["reduced_speed_areas"]:
        assert_in_bounds(rsa["x"], rsa["y"])
        assert_in_bounds(rsa["end_x"], rsa["end_y"])
    for item in elements["des_speed_decisions"]:
        assert_in_bounds(item["x"], item["y"])
    for det in elements["detectors"]:
        assert_in_bounds(det["x"], det["y"])
    for dcp in elements["data_collection_points"]:
        assert_in_bounds(dcp["x"], dcp["y"])
    for tt in elements["traveltime_sections_geo"]:
        assert_in_bounds(tt["start"]["x"], tt["start"]["y"])
        assert_in_bounds(tt["end"]["x"], tt["end"]["y"])
    for qc in elements["queue_counters"]:
        assert_in_bounds(qc["x"], qc["y"])
    for ss in elements["stop_signs"]:
        assert_in_bounds(ss["x"], ss["y"])
    for pt_stop in elements["pt_stops"]:
        assert_in_bounds(pt_stop["x"], pt_stop["y"])
    for area in elements["ped_areas"]:
        assert area["polygon"]
        for x, y in area["polygon"]:
            assert_in_bounds(x, y)

    # Every link now also carries per-lane widths.
    for link in net["links"]:
        assert link["lane_widths"]
        assert link["width_total"] == pytest.approx(sum(link["lane_widths"]), abs=0.01)

    # Backward compat: the pre-existing flat lists are untouched by this unit.
    assert net["traveltime_sections"] == [{"id": "1", "name": "Crossroads to Roundabout"}]
    assert net["detectors"] == []  # showcase defines no <dataCollectionMeasurement>
