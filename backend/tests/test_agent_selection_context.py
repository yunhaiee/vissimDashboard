def test_selecting_a_link_does_not_unlock_writing_to_it(tmp_path: Path):
    """Guardrail doctrine: a clicked object names a target, it never
    authorizes an action on it. With the default (refuse-all) write gate, a
    write decision is refused exactly as it is without a selection."""
    registry = ToolRegistry()
    executed: dict[str, bool] = {"write": False}

    from pydantic import BaseModel, ConfigDict

    class SetVolumeParams(BaseModel):
        model_config = ConfigDict(extra="forbid")
        input_no: str = "1"
        volume: int = 600

    @tool(
        name="set_vehicle_input_volume",
        tier="write",
        provider="vissim_com",
        params=SetVolumeParams,
        registry=registry,
    )
    def _set_volume(params: SetVolumeParams) -> dict[str, Any]:
        """Set a vehicle input volume."""
        executed["write"] = True
        return {"message": "wrote"}

    provider = FakeStructuredProvider(
        [
            _action("set_vehicle_input_volume", summary="교통량을 수정합니다"),
            _action("respond", summary="불가함을 안내합니다", answer="지금은 수정할 수 없습니다."),
        ]
    )

    result = run_agent_turn(
        "이 링크 교통량 600으로 바꿔줘",
        provider=provider,
        work_dir=tmp_path,
        session_id="s-nowrite",
        language="ko",
        registry=registry,
        selection=_demo_selection(link_ids=[DEMO_LINK_ID]),
    )

    assert executed["write"] is False
    records = read_trace(result.trace_path)
    refusals = [record for record in records if record["kind"] == "refusal"]
    assert len(refusals) == 1
    assert refusals[0]["payload"]["error_type"] == "tool_tier_forbidden"
    assert not any(record["kind"] == "action_start" for record in records)


