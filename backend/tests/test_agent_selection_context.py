def test_turn_without_selection_is_identical_to_one_with_selection_none(tmp_path: Path):
    """The critical regression gate: every pre-P7 caller (the whole existing
    orchestrator suite, eval/runner.py, the live-check tools) omits the new
    parameter, and must get exactly the turn it got before."""
    omitted = _respond_provider()
    result_omitted = run_agent_turn(
        "이 네트워크에 뭐가 있어?",
        provider=omitted,
        work_dir=tmp_path / "omitted",
        session_id="s-omitted",
        language="ko",
    )

    explicit = _respond_provider()
    result_explicit = run_agent_turn(
        "이 네트워크에 뭐가 있어?",
        provider=explicit,
        work_dir=tmp_path / "explicit",
        session_id="s-explicit",
        language="ko",
        selection=None,
    )

    assert omitted.first_prompt == explicit.first_prompt
    assert omitted.calls[0]["system"] == explicit.calls[0]["system"]
    assert omitted.calls[0]["tools"] == explicit.calls[0]["tools"]
    assert result_omitted.answer == result_explicit.answer
    assert result_omitted.kind == result_explicit.kind == "answer"
    assert result_omitted.steps == result_explicit.steps

    # And the prompt is literally the pre-P7 text: no stray block, no blank
    # line, no header left behind by an empty selection.
    assert omitted.first_prompt == (
        "Goal: 이 네트워크에 뭐가 있어?\n"
        "Language: ko\n"
        "Recent steps: none yet.\n"
        "Choose the single next action."
    )
    assert SELECTION_CONTEXT_KEY not in result_omitted.state.context


