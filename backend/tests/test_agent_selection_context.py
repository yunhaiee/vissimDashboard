def test_approved_rerun_replays_the_proposal_turns_selection(
    client, monkeypatch: pytest.MonkeyPatch, tmp_path: Path, approver_headers
):
    """``/agent/approve`` carries no selection of its own (the request only
    identifies a pending approval), so the proposal turn's is persisted in
    pending_approval.json — next to `message`/`language`, for the same
    replay-the-same-turn reason — and handed back to the approved re-run."""
    _session_work_dirs_at(monkeypatch, tmp_path)
    # A run-tier proposal: it pauses for approval exactly like a write, but
    # builds no VissimEditSession (the job queue owns COM), so no fake COM
    # session is needed here. 5 seeds keeps constraints.py's single-seed
    # warning out of a test that is not about warnings.
    provider = FakeStructuredProvider(
        [
            _action(
                "run_simulation",
                summary="실행을 제안합니다",
                duration_s=300,
                random_seeds=[1, 2, 3, 4, 5],
            ),
            # The approve turn: end immediately, so nothing dispatches — this
            # test is about the PROMPT the approved re-run's planner saw.
            _action("respond", summary="확인했습니다", answer="확인했습니다."),
        ]
    )
    monkeypatch.setattr(assistant_endpoint, "_default_provider", lambda: provider)

    propose = client.post(
        "/api/assistant/agent/query/stream",
        json={
            "message": "이 링크 기준으로 5분 돌려줘",
            "response_language": "ko",
            "selected_link_ids": [DEMO_LINK_ID],
        },
    )
    assert propose.status_code == 200
    events = [json.loads(line) for line in propose.text.splitlines() if line.strip()]
    approval = next(event for event in events if event["type"] == "approval_request")
    session_id = events[-1]["response"]["session_id"]

    pending = json.loads(
        (tmp_path / session_id / "pending_approval.json").read_text(encoding="utf-8")
    )
    assert pending["selection"]["links"][0]["name"] == DEMO_LINK_NAME

    approve = client.post(
        "/api/assistant/agent/approve",
        json={
            "session_id": session_id,
            "approval_id": approval["approval_id"],
            "approved": True,
        },
        headers=approver_headers,
    )

    assert approve.status_code == 200
    approve_prompt = provider.calls[-1]["messages"][0]["content"]
    assert "[사용자가 화면에서 선택한 객체]" in approve_prompt
    assert DEMO_LINK_NAME in approve_prompt


