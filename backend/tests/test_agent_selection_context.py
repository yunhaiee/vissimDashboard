class FakeStructuredProvider:
    """Canned (action, meta) queue implementing the ``generate_structured``
    seam, recording every call — see test_agent_orchestrator.py's identical
    fixture for the full rationale."""

    def __init__(self, queue: list[tuple[dict[str, Any] | None, dict[str, Any]]]) -> None:
        self._queue = list(queue)
        self.calls: list[dict[str, Any]] = []

    def generate_structured(
        self,
        messages: list[dict[str, Any]],
        tools: list[dict[str, Any]],
        schema: dict[str, Any] | None = None,
        *,
        system: str | None = None,
        max_tokens: int | None = None,
    ) -> tuple[dict[str, Any] | None, dict[str, Any]]:
        self.calls.append(
            {"messages": messages, "tools": tools, "schema": schema, "system": system}
        )
        if not self._queue:
            raise AssertionError("FakeStructuredProvider queue exhausted unexpectedly")
        return self._queue.pop(0)

    @property
    def first_prompt(self) -> str:
        return self.calls[0]["messages"][0]["content"]


def _action(
    tool_name: str, *, summary: str = "확인합니다", **params: Any
) -> tuple[dict[str, Any], dict[str, Any]]:
    params["summary"] = summary
    return {"tool": tool_name, "params": params}, {"mode": "fake", "fallback_rung": 0}


def _respond_provider(answer: str = "확인했습니다.") -> FakeStructuredProvider:
    return FakeStructuredProvider([_action("respond", summary="정리했습니다", answer=answer)])


def _demo_selection(**kwargs: Any) -> dict[str, Any]:
    """A selection resolved against the real demo network."""
    selection = build_selection_context(inpx_path=DEMO_INPX, **kwargs)
    assert selection is not None
    return selection


