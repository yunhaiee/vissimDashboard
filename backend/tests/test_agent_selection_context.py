"""P7 — the on-screen selection reaching AGENT mode.

P6 wired clicked network components into the plain assistant + curate paths;
the tool-executing agent got nothing (``AgentQueryRequest`` carried only
``{message, response_language, session_id}``). This file covers the four
halves of closing that gap:

1. **Inertness.** ``run_agent_turn`` without ``selection`` (and with an
   explicit ``selection=None``) produces a byte-identical planner prompt and
   an identical turn — the existing orchestrator suite must keep passing
   untouched, and that is asserted here directly rather than only implied.
2. **Surfacing.** A selection lands in the planner's per-iteration user
   message as ONE delimited block carrying resolved identities (link name /
   lanes / length, node name, element + owning link), with ids the network
   does not contain stated as not-found rather than dropped.
3. **Context only.** The same selection changes neither the system prompt,
   nor the offered tool defs, nor the write gate's refusal of a write-tier
   action. Clicking a link never unlocks editing it.
4. **Resolution precedence.** The endpoint resolves against the SESSION's
   working copy when one exists, and the active dataset otherwise.

No LLM anywhere: the planner is driven with the same canned
``generate_structured`` fake ``test_agent_orchestrator.py`` uses, and network
resolution reads the real demo ``.inpx`` (never live Vissim).
"""
