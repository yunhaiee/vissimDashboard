def test_agent_query_resolves_the_selection_against_the_session_working_copy(
    client, monkeypatch: pytest.MonkeyPatch, tmp_path: Path
):
    """A session that has already been cloned/edited must have its selection
    read from THAT working copy — the file the P2 network view renders and the
    turn's own read tools are pointed at — not from the pristine dataset."""
    session_id = "abcdef123456"
    _session_work_dirs_at(monkeypatch, tmp_path)
