def test_selection_reaches_the_planner_prompt_with_resolved_identities(tmp_path: Path):
    selection = _demo_selection(
        node_ids=[DEMO_NODE_ID, "9999"],
        link_ids=[DEMO_LINK_ID, DEMO_CONNECTOR_ID, "9999"],
        element={"type": "vehicle_inputs", "id": "1", "name": None, "link": None},
        scenario_ids=["base_am"],
    )
    provider = _respond_provider()

    result = run_agent_turn(
        "이 링크 차로 수 알려줘",
        provider=provider,
        work_dir=tmp_path,
        session_id="s-selection",
        language="ko",
        selection=selection,
    )

    prompt = provider.first_prompt
    assert "[사용자가 화면에서 선택한 객체]" in prompt, "expected the delimited selection block"
    # Resolved identity, not the raw id the client sent.
    assert f'- link {DEMO_LINK_ID} "{DEMO_LINK_NAME}" lanes=3 length=280m' in prompt
    assert f"- connector {DEMO_CONNECTOR_ID}" in prompt and "from=101 to=140" in prompt
    assert f'- node {DEMO_NODE_ID} "{DEMO_NODE_NAME}"' in prompt
    assert '- element vehicle_inputs 1 "Main St EB" link=101' in prompt
    assert "- scenarios: base_am" in prompt
    # An id this network does not contain is STATED, never silently dropped.
    assert prompt.count("- link 9999: not found in this network") == 1
    assert "- node 9999: not found in this network" in prompt
    # Directly under the goal, ahead of history — the goal's "이 링크" is
    # meaningless without it.
    assert prompt.index("[사용자가 화면에서 선택한 객체]") < prompt.index("Recent steps")
    assert result.kind == "answer"


def test_selection_block_stays_compact(tmp_path: Path):
    """This block is re-sent on EVERY planner call, so its size is a real
    prompt-cost decision: one short line per object, capped by the request
    boundary's own caps."""
    selection = _demo_selection(
        node_ids=[DEMO_NODE_ID, "2"],
        link_ids=[DEMO_LINK_ID, DEMO_CONNECTOR_ID],
        element={"type": "vehicle_inputs", "id": "1", "name": None, "link": None},
    )
    lines = render_selection_block(selection)

    assert len(lines) == 1 + 2 + 2 + 1  # header + nodes + links + element
    assert all(len(line) <= 160 for line in lines), lines
    # A pathological name from the parsed network is truncated, not pasted.
    long_name = render_selection_block({"links": [{"id": "1", "name": "x" * 400}]})
    assert all(len(line) <= 160 for line in long_name), long_name


def test_selection_is_replaced_not_merged_across_turns_of_one_session(tmp_path: Path):
    """The client re-sends its current selection every turn (M3.3 reloads the
    session's state.json, which carries the PREVIOUS turn's selection), so a
    turn with no selection must actively CLEAR the stale one — otherwise a
    deselected link would haunt every later prompt in the conversation."""
    first = _respond_provider()
    run_agent_turn(
        "이 링크 설명해줘",
        provider=first,
        work_dir=tmp_path,
        session_id="s-sticky",
        language="ko",
        selection=_demo_selection(link_ids=[DEMO_LINK_ID]),
    )
    assert DEMO_LINK_NAME in first.first_prompt
    # Persisted with the session (state.context is already JSON-serialized by
    # session_store — no new storage shape was invented for this).
    persisted = json.loads(session_store.state_path(tmp_path).read_text(encoding="utf-8"))
    assert persisted["context"][SELECTION_CONTEXT_KEY]["links"][0]["name"] == DEMO_LINK_NAME

    second = _respond_provider()
    run_agent_turn(
        "그럼 전체 네트워크는?",
        provider=second,
        work_dir=tmp_path,
        session_id="s-sticky",
        language="ko",
    )
    assert "[사용자가 화면에서 선택한 객체]" not in second.first_prompt
    assert DEMO_LINK_NAME not in second.first_prompt

    third = _respond_provider()
    run_agent_turn(
        "이 노드는?",
        provider=third,
        work_dir=tmp_path,
        session_id="s-sticky",
        language="ko",
        selection=_demo_selection(node_ids=[DEMO_NODE_ID]),
    )
    assert DEMO_NODE_NAME in third.first_prompt
    assert DEMO_LINK_NAME not in third.first_prompt, "the earlier turn's link must not linger"


