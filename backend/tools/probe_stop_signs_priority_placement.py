def _xml_stop_signs(inpx_path: Path) -> list[dict[str, Any]]:
    root = ET.parse(inpx_path).getroot()
    return [dict(el.attrib) for el in root.findall(".//stopSign")]


def _xml_priority_rules(inpx_path: Path) -> list[dict[str, Any]]:
    root = ET.parse(inpx_path).getroot()
    result = []
    for pr in root.findall(".//priorityRule"):
        markers = [dict(m.attrib) for m in pr.findall(".//conflictMarker")]
        result.append({**dict(pr.attrib), "markers": markers})
    return result


def _try_add(container: Any, method_name: str, *arg_sets: tuple) -> tuple[Any, tuple | None]:
    """Try ``container.<method_name>(*args)`` for each ``arg_sets`` entry in
    order, returning the first that succeeds (object, the args that worked)
    -- ``(None, None)`` if every candidate raised."""
    method = getattr(container, method_name, None)
    if method is None:
        _log(f"        Container has no {method_name!r} method at all (hasattr fails).")
        return None, None
    for args in arg_sets:
        try:
            result = method(*args)
            _log(f"        [WORKS] {method_name}{args!r} -> {result!r}")
            return result, args
        except Exception as exc:
            _log(f"        [no]    {method_name}{args!r} -> {type(exc).__name__}: {exc}")
    return None, None


